"""Brand kit for a generated website: a curated palette and font pairing, a wordmark, and the reading direction.

Deliberately NOT generated by a model and NOT chosen by business type. A palette is picked from a short list of hand-checked looks by a stable hash of the
business name, so the same business always gets the same look and two different businesses usually get different ones. Every look is checked in tests for
legible contrast (body text on the page, white text on the primary colour), so a generated site never ships pale-grey-on-white. The owner can change every
value afterwards in the theme editor; `logo_text` is a plain-text wordmark because there is no image upload to host or to get wrong.

No vertical-name literal appears here (tests/test_website_no_vertical_hardcoding.py).
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass


@dataclass(frozen=True)
class BrandLook:
    key: str
    label: str
    primary: str  # buttons, headings band, the step numbers: white text sits on it
    accent: str  # rules, highlights, focus: never used as text
    surface: str  # alternating bands and cards
    text: str  # body text on the page background
    heading_font: str
    body_font: str


LOOKS: tuple[BrandLook, ...] = (
    BrandLook("harbour", "Harbour", "#14304F", "#E0A030", "#F2F5F9", "#14243A", "Playfair Display", "Inter"),
    BrandLook("lagoon", "Lagoon", "#0F5C5A", "#E27D60", "#EFF6F5", "#12312F", "DM Sans", "DM Sans"),
    BrandLook("orchid", "Orchid", "#4B2A5E", "#D4A24C", "#F6F1F8", "#2A1636", "Merriweather", "Inter"),
    BrandLook("cedar", "Cedar", "#234A3A", "#C9A66B", "#F2F5F0", "#17261F", "Source Serif 4", "Inter"),
    BrandLook("slate", "Slate", "#27364B", "#4FA3D1", "#F1F4F8", "#1B2635", "Poppins", "Inter"),
)

# Arabic-first sites read right to left and need a face that actually has the letters.
RTL_LOOK_FONTS = ("Cairo", "Cairo")

_ARABIC = re.compile(r"[؀-ۿݐ-ݿﭐ-﷿ﹰ-﻿]")


def look_by_key(key: str) -> BrandLook | None:
    return next((look for look in LOOKS if look.key == key), None)


def pick_look(business_name: str) -> BrandLook:
    digest = hashlib.sha256(business_name.strip().lower().encode("utf-8")).digest()
    return LOOKS[digest[0] % len(LOOKS)]


def is_arabic_first(*texts: str | None) -> bool:
    """True when most of the letters in what the owner wrote are Arabic. Mixed names ("Al Noor Clinic") stay left to right."""
    arabic = other = 0
    for text in texts:
        for ch in text or "":
            if _ARABIC.match(ch):
                arabic += 1
            elif ch.isalpha():
                other += 1
    return arabic > 0 and arabic >= other


def _luminance(hex_color: str) -> float:
    def channel(c: int) -> float:
        v = c / 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4

    r, g, b = (int(hex_color[i : i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast_ratio(a: str, b: str) -> float:
    la, lb = _luminance(a), _luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def theme_for(business_name: str, *, texts: tuple[str | None, ...] = ()) -> dict:
    """Theme tokens for a generated site (a dict `ThemeTokens` validates)."""
    look = pick_look(business_name)
    rtl = is_arabic_first(business_name, *texts)
    heading, body = RTL_LOOK_FONTS if rtl else (look.heading_font, look.body_font)
    return {
        "primary_color": look.primary,
        "secondary_color": look.accent,
        "background_color": "#FFFFFF",
        "text_color": look.text,
        "surface_color": look.surface,
        "heading_font": heading,
        "body_font": body,
        "radius_scale": "MD",
        "shadow_scale": "SM",
        "spacing_scale": "SPACIOUS",
        "text_direction": "RTL" if rtl else "LTR",
        "logo_text": business_name.strip()[:40] or None,
    }


_STEP_SPLIT = re.compile(r"\s*(?:\r?\n|;|\s->\s|\s→\s|(?<=[.!?])\s+(?=\d+[.)]\s)|(?:^|\s)\d+[.)]\s+)\s*")


def split_steps(text: str) -> list[str]:
    """Break a journey the owner wrote as one block ("1. Enquire 2. Talk to us ...", or one step per line) into separate steps. A single sentence stays one."""
    parts = [p.strip(" -•\t") for p in _STEP_SPLIT.split(text) if p and p.strip(" -•\t")]
    return [p[:200] for p in parts][:8]
